export interface MenuTemplateThemeConfig {
  pageBg: string;               // PDF background color
  cardBg: string;               // Category bar / item background
  cardBorderColor: string;      // Category border outline
  frameColor: string;           // Outer page decorative frame
  innerFrameColor?: string;     // Inner fine hairline frame
  logoBorderColor: string;      // Outline color for centered logo
  logoBgColor: string;          // Background circle for logo
  textPrimary: string;          // Main title, category name, dish name, price
  textSecondary: string;        // Branch details, descriptions, notes
  textAccent: string;           // Taglines, badges, special accents
  dividerColor: string;         // Line dividers between items
  headerBannerStyle: 'solid-card' | 'outlined-card' | 'underlined' | 'vintage-ornate' | 'modern-pill';
  fontFamilyHeader: 'Helvetica-Bold' | 'Times-Bold' | 'Courier-Bold';
  fontFamilyBody: 'Helvetica' | 'Times-Roman' | 'Courier';
  fontFamilyItalic: 'Helvetica-Oblique' | 'Times-Italic' | 'Courier-Oblique';
  foodTypeColors: {
    veg: string;
    nonVeg: string;
    egg: string;
    vegan: string;
  };
}

