  id: string;
  name: string;
  subtitle: string;
  category: 'dark' | 'light' | 'vintage' | 'luxury' | 'modern';
  layoutStyle: 'centered' | 'classic-boxed' | 'ornate-vintage' | 'modern-minimal' | 'two-column-look';
